#include<bits/stdc++.h>
using namespace std;

int main(){
    int input = 0;
    cin>>input;
    int i,j;
    for(i=0;i<input;i++){
        for(j=0;j<input;j++){
            cout<<"*";
        }
        cout<<"\n";
    }
    return 0;
}